#!/usr/bin/env python3
"""Validate aggregate JSON contracts using the JSON Schema subset declared here."""
from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def json_type_ok(value, expected):
    expected_types = expected if isinstance(expected, list) else [expected]
    for name in expected_types:
        if name == "object" and isinstance(value, dict):
            return True
        if name == "array" and isinstance(value, list):
            return True
        if name == "string" and isinstance(value, str):
            return True
        if name == "integer" and isinstance(value, int) and not isinstance(value, bool):
            return True
        if name == "number" and isinstance(value, (int, float)) and not isinstance(value, bool):
            return True
        if name == "boolean" and isinstance(value, bool):
            return True
        if name == "null" and value is None:
            return True
    return False


def validate(value, schema, pointer="$", errors=None):
    errors = [] if errors is None else errors
    if "type" in schema and not json_type_ok(value, schema["type"]):
        errors.append(f"{pointer}: expected {schema['type']}")
        return errors
    if "const" in schema and value != schema["const"]:
        errors.append(f"{pointer}: expected constant {schema['const']!r}")
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{pointer}: value outside enum")
    if isinstance(value, dict):
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{pointer}: missing required property {key!r}")
        props = schema.get("properties", {})
        if schema.get("additionalProperties") is False:
            for key in value.keys() - props.keys():
                errors.append(f"{pointer}: unexpected property {key!r}")
        for key, subschema in props.items():
            if key in value:
                validate(value[key], subschema, f"{pointer}.{key}", errors)
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{pointer}: fewer than minItems={schema['minItems']}")
        item_schema = schema.get("items")
        if item_schema:
            for index, item in enumerate(value):
                validate(item, item_schema, f"{pointer}[{index}]", errors)
    return errors


def load_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def main():
    schema_pairs = [
        ("metadata/ARTIFACT_IDENTITY.json", "schemas/artifact-identity.schema.json"),
        ("metadata/RIGHTSHOLDER_ATTESTATION.json", "schemas/owner-attestation.schema.json"),
        ("LICENSES/AGGREGATE_FILE_LICENSE_MAP.json", "schemas/aggregate-file-license-map.schema.json"),
        ("specifications/SYSTEM_SPECIFICATION_v3.5.json", "schemas/system-specification.schema.json"),
        ("specifications/INTEGRATION_CONTRACT_v1.0.json", "schemas/integration-contract.schema.json"),
        ("specifications/QH256_MAPPING_PROFILE_v3.5.json", "schemas/mapping-profile.schema.json"),
        ("metadata/GATE_STATUS.json", "schemas/gate-status.schema.json"),
        ("zenodo/METADATA_DRAFT.json", "schemas/zenodo-metadata-draft.schema.json"),
        ("specifications/RELEASE_GATE_PROFILE_v3.5.json", "schemas/release-gate-profile.schema.json"),
        ("MANIFEST.json", "schemas/aggregate-manifest.schema.json"),
        ("Index.json", "schemas/index.schema.json"),
    ]
    failures = []
    for schema_path in sorted((ROOT / "schemas").glob("*.schema.json")):
        try:
            schema = load_json(schema_path)
            if schema_path.name != "evidence-record.schema.json" and schema.get("$schema") != "https://json-schema.org/draft/2020-12/schema":
                failures.append(f"{schema_path.relative_to(ROOT)}: unexpected JSON Schema dialect")
        except Exception as exc:
            failures.append(f"{schema_path.relative_to(ROOT)}: invalid schema JSON: {exc}")
    for instance_rel, schema_rel in schema_pairs:
        try:
            instance_path = ROOT / instance_rel
            if not instance_path.is_file():
                if instance_rel in {"MANIFEST.json", "Index.json"}:
                    print(f"SCHEMA_DEFERRED {instance_rel} (generated by refresh-integrity)")
                    continue
                raise FileNotFoundError(instance_path)
            instance = load_json(instance_path)
            schema = load_json(ROOT / schema_rel)
            errors = validate(instance, schema)
            failures.extend(f"{instance_rel}: {error}" for error in errors)
            if not errors:
                print(f"SCHEMA_PASS {instance_rel} -> {schema_rel}")
        except Exception as exc:
            failures.append(f"{instance_rel} -> {schema_rel}: {exc}")

    # Parse every bundled JSON document, including preserved component records.
    parsed = 0
    for path in ROOT.rglob("*.json"):
        if any(part in {"build", ".git", "__pycache__"} for part in path.parts):
            continue
        try:
            load_json(path)
            parsed += 1
        except Exception as exc:
            failures.append(f"{path.relative_to(ROOT)}: invalid JSON: {exc}")

    profile = load_json(ROOT / "specifications/RELEASE_GATE_PROFILE_v3.5.json")
    gate_ids = [gate["gate_id"] for gate in profile["gates"]]
    if len(gate_ids) != len(set(gate_ids)):
        failures.append("RELEASE_GATE_PROFILE_v3.5.json: duplicate gate ID")
    id_set = set(gate_ids)
    for gate in profile["gates"]:
        missing = set(gate["depends_on"]) - id_set
        if missing:
            failures.append(f"{gate['gate_id']}: unresolved dependencies {sorted(missing)}")
    for release_profile in profile["release_profiles"]:
        missing = set(release_profile["required_gates"]) - id_set
        if missing:
            failures.append(f"{release_profile['profile_id']}: unknown gates {sorted(missing)}")

    # The owner-ratified file map must classify every package file exactly once.
    try:
        license_map = load_json(ROOT / "LICENSES/AGGREGATE_FILE_LICENSE_MAP.json")
        paths = [entry["path"] for entry in license_map["entries"]]
        if len(paths) != len(set(paths)):
            failures.append("AGGREGATE_FILE_LICENSE_MAP.json: duplicate path")
        if license_map["entry_count"] != len(paths):
            failures.append("AGGREGATE_FILE_LICENSE_MAP.json: entry_count mismatch")
        actual = {p.relative_to(ROOT).as_posix() for p in ROOT.rglob("*") if p.is_file() and not any(part in {".git", "build", "__pycache__"} for part in p.relative_to(ROOT).parts)}
        if set(paths) != actual:
            failures.append(f"AGGREGATE_FILE_LICENSE_MAP.json: path coverage differs; unmapped={sorted(actual-set(paths))[:5]} stale={sorted(set(paths)-actual)[:5]}")
        print(f"LICENSE_MAP_COVERAGE_PASS files={len(paths)}")
    except Exception as exc:
        failures.append(f"AGGREGATE_FILE_LICENSE_MAP.json: {exc}")
    graph = {gate["gate_id"]: set(gate["depends_on"]) for gate in profile["gates"]}
    visiting, visited = set(), set()
    def visit(gate_id):
        if gate_id in visiting:
            failures.append(f"RELEASE_GATE_PROFILE_v3.5.json: dependency cycle at {gate_id}")
            return
        if gate_id in visited:
            return
        visiting.add(gate_id)
        for dependency in graph.get(gate_id, ()):
            visit(dependency)
        visiting.remove(gate_id)
        visited.add(gate_id)
    for gate_id in graph:
        visit(gate_id)
    print(f"JSON_PARSE_PASS files={parsed}")
    print(f"GATE_PROFILE_PASS gates={len(gate_ids)} profiles={len(profile['release_profiles'])}")
    if failures:
        for failure in failures:
            print(f"FAIL {failure}", file=sys.stderr)
        return 1
    print("CONTRACT_VALIDATION=PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
